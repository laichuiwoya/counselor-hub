DROP DATABASE IF EXISTS counselor_db;
CREATE DATABASE counselor_db DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE counselor_db;

/* ============================================================
   用户表（辅导员/管理员）
   ============================================================ */
DROP TABLE IF EXISTS sys_user;
CREATE TABLE sys_user (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    username    VARCHAR(50)  NOT NULL COMMENT '登录账号',
    password    VARCHAR(100) NOT NULL COMMENT '密码（MD5）',
    real_name   VARCHAR(50)  NOT NULL COMMENT '真实姓名',
    role        VARCHAR(20)  NOT NULL DEFAULT 'counselor' COMMENT '角色：admin管理员 counselor辅导员',
    phone       VARCHAR(20)           COMMENT '手机号',
    email       VARCHAR(50)           COMMENT '邮箱',
    avatar      VARCHAR(255)          COMMENT '头像路径',
    status      TINYINT      NOT NULL DEFAULT 1 COMMENT '状态 1启用 0禁用',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='系统用户表';

/* ============================================================
   学生基本表
   ============================================================ */
DROP TABLE IF EXISTS student;
CREATE TABLE student (
    id               BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    student_no       VARCHAR(20)  NOT NULL COMMENT '学号',
    name             VARCHAR(50)  NOT NULL COMMENT '姓名',
    gender           VARCHAR(4)   NOT NULL COMMENT '性别 男/女',
    college          VARCHAR(80)  NOT NULL COMMENT '学院',
    major            VARCHAR(80)  NOT NULL COMMENT '专业',
    class_name       VARCHAR(50)  NOT NULL COMMENT '班级',
    grade            VARCHAR(10)           COMMENT '年级',
    dorm_building    VARCHAR(20)           COMMENT '宿舍楼',
    dorm_room        VARCHAR(20)           COMMENT '宿舍号',
    phone            VARCHAR(20)           COMMENT '手机号',
    id_card          VARCHAR(18)           COMMENT '身份证号',
    native_place     VARCHAR(100)          COMMENT '籍贯',
    political_status VARCHAR(20)           COMMENT '政治面貌',
    counselor_id     BIGINT                COMMENT '辅导员ID',
    status           VARCHAR(20)  NOT NULL DEFAULT '在读' COMMENT '在读/休学/毕业/退学',
    create_time      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_student_no (student_no),
    KEY idx_counselor (counselor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='学生基本表';

/* ============================================================
   学生奖惩表
   ============================================================ */
DROP TABLE IF EXISTS reward_punishment;
CREATE TABLE reward_punishment (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    student_id  BIGINT       NOT NULL COMMENT '学生ID',
    type        VARCHAR(10)  NOT NULL COMMENT '类型 奖励/处分',
    level       VARCHAR(30)           COMMENT '级别（如校级一等奖学金/警告/记过）',
    name        VARCHAR(100)         COMMENT '奖惩名称',
    reason      VARCHAR(500)         COMMENT '事由',
    occur_date  DATE         NOT NULL COMMENT '发生日期',
    operator    VARCHAR(50)           COMMENT '经办人',
    status      VARCHAR(10)  NOT NULL DEFAULT '生效' COMMENT '生效/撤销',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_student (student_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='学生奖惩表';

/* ============================================================
   工作提示表
   ============================================================ */
DROP TABLE IF EXISTS work_reminder;
CREATE TABLE work_reminder (
    id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    title        VARCHAR(100) NOT NULL COMMENT '标题',
    content      VARCHAR(1000)         COMMENT '内容',
    type         VARCHAR(30)           COMMENT '类型 会议/材料/谈话/检查/其他',
    priority     VARCHAR(10)  NOT NULL DEFAULT '中' COMMENT '优先级 高/中/低',
    due_date     DATE                  COMMENT '截止日期',
    status       VARCHAR(10)  NOT NULL DEFAULT '待办' COMMENT '待办/进行中/已完成',
    counselor_id BIGINT                COMMENT '辅导员ID',
    create_time  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_counselor (counselor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='工作提示表';

/* ============================================================
   工作流程纪要表
   ============================================================ */
DROP TABLE IF EXISTS workflow_minutes;
CREATE TABLE workflow_minutes (
    id            BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    title         VARCHAR(100) NOT NULL COMMENT '主题',
    category      VARCHAR(30)           COMMENT '类别 主题班会/学生谈话/走访宿舍/专题会议/其他',
    content       TEXT                  COMMENT '详细内容',
    participants  VARCHAR(500)          COMMENT '参与人员',
    meeting_date  DATE         NOT NULL COMMENT '会议日期',
    location      VARCHAR(100)          COMMENT '地点',
    summary       VARCHAR(500)          COMMENT '纪要小结',
    counselor_id  BIGINT                COMMENT '辅导员ID',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_counselor (counselor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='工作流程纪要表';

/* ============================================================
   学生档案表
   ============================================================ */
DROP TABLE IF EXISTS student_archive;
CREATE TABLE student_archive (
    id            BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    student_id    BIGINT       NOT NULL COMMENT '学生ID',
    archive_type  VARCHAR(30)  NOT NULL COMMENT '档案类型 入学登记表/成绩单/奖惩材料/实习材料/毕业材料/其他',
    archive_name  VARCHAR(100)          COMMENT '档案名称',
    file_path     VARCHAR(255)          COMMENT '文件存储路径',
    description   VARCHAR(500)          COMMENT '说明',
    upload_date   DATE         NOT NULL COMMENT '归档日期',
    operator      VARCHAR(50)           COMMENT '经办人',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_student (student_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='学生档案表';

